export function resolvePengliIssue(themeNumber: number, themePage: number) {
  const issues = PENGLI_THEME_ISSUES[themeNumber] ?? [];
  let resolved: PengliIssue | null = null;
  for (const [page, title] of issues) {
    if (page > themePage) break;
    resolved = { page, title };
  }
  return resolved;
}

export function detectPengliBodyRole(text: string) {
  const normalized = text.replace(/\s+/gu, "");
  if (/考點直擊站/u.test(normalized) && /考點破解/u.test(normalized)) return "考點直擊站與考點破解";
  if (/考點直擊站/u.test(normalized)) return "考點直擊站";
  if (/考點破解/u.test(normalized)) return "考點破解";
  if (/問題意識/u.test(normalized)) return "問題意識";
  if (/學說見解/u.test(normalized)) return "學說見解";
  if (/實務見解/u.test(normalized)) return "實務見解";
  if (/擬答/u.test(normalized)) return "擬答";
  if (/概說/u.test(normalized)) return "概說";
  return "考點正文";
}
